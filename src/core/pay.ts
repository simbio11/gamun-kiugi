/** 명목 임금 상승률: 물가·집값이 오르듯 임금도 오른다 (연 2.5%) */
export const WAGE_GROWTH = 0.025;
export const BASE_YEAR = 2025;
export const wageIndex = (year: number) => Math.pow(1 + WAGE_GROWTH, Math.max(0, year - BASE_YEAR));

